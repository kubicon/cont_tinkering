"""Train one cell of the magnet grid over several seeds, writing checkpoints per seed.

    python experiments/failing_gaussian_wo_magnet/rerun/run_cell.py mp_magnet_ppo --seeds 0 1 2 3 4
    python experiments/failing_gaussian_wo_magnet/rerun/run_cell.py rot2_nomagnet_sampled \\
        --seeds 0 1 2 --max-parallel 3 --out data/failing_gaussian_rerun_seeds

A *cell* is one `<domain>_<magnet|nomagnet>_<engine>.yaml` in this directory; that file
stays the single source of every hyperparameter. For each seed this script writes a copy
of it with only `train.seed` and `train.checkpoint_dir` replaced, and runs the cell's
entry point (`train.py` for `ppo`, `run_idealized.py` otherwise) on that copy:

    <out>/<cell>/seed<k>/
        run_config.yaml          the config actually run (train.py also copies it to config.yaml)
        train.log                the run's stdout/stderr
        0.pkl .. 200.pkl         ppo cells
        idealized_history.json   idealized / sampled cells

What the seed changes: the network initialization and the PPO batches for `ppo`, the
Monte-Carlo payoff draws for `sampled` (`idealized.sample_seed: null` -> `train.seed`).
The `idealized` cells are deterministic -- quadrature payoffs, initialization from the
config -- so every seed would be the same run; only the first seed is run for them.

A seed whose directory already holds a finished run is skipped unless `--overwrite`, so
a job that ran out of wall-time can be resubmitted and picks up where it stopped. Seeds
run as separate processes, `--max-parallel` at a time, with each one's thread pool
capped so parallel seeds do not measure contention with each other.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
CONFIG_DIR = Path(__file__).resolve().parent
DEFAULT_OUT = "data/failing_gaussian_rerun_seeds"
DEFAULT_SEEDS = (0, 1, 2, 3, 4)
RUN_CONFIG_NAME = "run_config.yaml"
LOG_NAME = "train.log"


def all_cells() -> list[str]:
    return sorted(p.stem for p in CONFIG_DIR.glob("*.yaml"))


def engine_of(cell: str) -> str:
    return cell.rsplit("_", 1)[1]


def is_deterministic(cell: str) -> bool:
    """No sampling anywhere in the run, so a second seed would reproduce the first."""
    return engine_of(cell) == "idealized"


def entry_point(cell: str) -> str:
    return "train.py" if engine_of(cell) == "ppo" else "run_idealized.py"


def seed_dir(out: Path, cell: str, seed: int) -> Path:
    return out / cell / f"seed{seed}"


def is_finished(run_dir: Path, cell: str, steps: int) -> bool:
    """The last thing each entry point writes is there."""
    if engine_of(cell) == "ppo":
        return (run_dir / f"{steps}.pkl").exists()
    return (run_dir / "idealized_history.json").exists()


def write_seed_config(cell: str, seed: int, run_dir: Path) -> tuple[Path, int]:
    """The cell's config with this seed's `train.seed` / `train.checkpoint_dir` folded in."""
    with open(CONFIG_DIR / f"{cell}.yaml") as f:
        config = yaml.safe_load(f)
    config["train"]["seed"] = seed
    # Relative to the repo root, which is where the entry point runs.
    config["train"]["checkpoint_dir"] = os.path.relpath(run_dir, REPO_ROOT)
    run_dir.mkdir(parents=True, exist_ok=True)
    path = run_dir / RUN_CONFIG_NAME
    with open(path, "w") as f:
        f.write(f"# Generated by {Path(__file__).name} from {cell}.yaml, seed {seed}.\n")
        yaml.safe_dump(config, f, sort_keys=False)
    return path, int(config["train"]["steps"])


def child_environment(threads: int) -> dict:
    env = dict(os.environ)
    env["PYTHONUNBUFFERED"] = "1"   # per-step progress reaches the log as it happens
    env["OMP_NUM_THREADS"] = str(threads)
    env["MKL_NUM_THREADS"] = str(threads)
    env["XLA_FLAGS"] = (env.get("XLA_FLAGS", "")
                        + f" --xla_cpu_multi_thread_eigen=true intra_op_parallelism_threads={threads}"
                        ).strip()
    return env


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cell", choices=all_cells(), help="config stem in this directory")
    ap.add_argument("--seeds", nargs="+", type=int, default=list(DEFAULT_SEEDS))
    ap.add_argument("--out", default=DEFAULT_OUT, help="root of the per-seed checkpoint tree")
    ap.add_argument("--max-parallel", type=int, default=1, help="seeds run at once")
    ap.add_argument("--threads-per-seed", type=int, default=0,
                    help="thread cap per seed (default: cores / --max-parallel)")
    ap.add_argument("--overwrite", action="store_true", help="rerun seeds that already finished")
    args = ap.parse_args()

    out = (REPO_ROOT / args.out).resolve()
    seeds = list(dict.fromkeys(args.seeds))
    if is_deterministic(args.cell) and len(seeds) > 1:
        print(f"{args.cell} is deterministic; running seed {seeds[0]} only "
              f"(dropping {seeds[1:]})")
        seeds = seeds[:1]

    cores = len(os.sched_getaffinity(0)) if hasattr(os, "sched_getaffinity") else (os.cpu_count() or 4)
    threads = args.threads_per_seed or max(1, cores // max(args.max_parallel, 1))
    env = child_environment(threads)
    script = entry_point(args.cell)

    queue = []
    for seed in seeds:
        run_dir = seed_dir(out, args.cell, seed)
        config_path, steps = write_seed_config(args.cell, seed, run_dir)
        if not args.overwrite and is_finished(run_dir, args.cell, steps):
            print(f"  seed {seed}: already finished in {os.path.relpath(run_dir, REPO_ROOT)}, skipping")
            continue
        queue.append((seed, run_dir, config_path))

    print(f"{args.cell}: {len(queue)} seed(s) via {script}, {args.max_parallel} at a time, "
          f"{threads} threads each -> {os.path.relpath(out / args.cell, REPO_ROOT)}")

    running: list[tuple[int, subprocess.Popen, object, float]] = []
    failed: list[int] = []

    def reap() -> None:
        """Drop every finished process from `running`, recording failures."""
        for item in list(running):
            seed, proc, handle, started = item
            if proc.poll() is None:
                continue
            handle.close()
            running.remove(item)
            status = "ok" if proc.returncode == 0 else f"FAILED (exit {proc.returncode})"
            print(f"  seed {seed}: {status} after {time.time() - started:.0f} s", flush=True)
            if proc.returncode != 0:
                failed.append(seed)

    for seed, run_dir, config_path in queue:
        while len(running) >= max(args.max_parallel, 1):
            time.sleep(2.0)
            reap()
        handle = open(run_dir / LOG_NAME, "w")
        command = [sys.executable, script, os.path.relpath(config_path, REPO_ROOT)]
        print(f"  seed {seed}: launch {' '.join(command[1:])}", flush=True)
        running.append((seed, subprocess.Popen(command, cwd=REPO_ROOT, env=env, stdout=handle,
                                               stderr=subprocess.STDOUT), handle, time.time()))
    while running:
        time.sleep(2.0)
        reap()

    if failed:
        raise SystemExit(f"{args.cell}: seeds {sorted(failed)} failed; see their {LOG_NAME}")
    print(f"{args.cell}: done")


if __name__ == "__main__":
    main()
